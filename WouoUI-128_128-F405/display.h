#ifndef DISPLAY_H
#define DISPLAY_H

#include "config.h"
#include <SPI.h>

/************************************* 显示模块 *************************************/

/*
 * U8g2屏幕对象
 * 
 * 夏普LS013B7DH03 128x128 Memory LCD
 * 4线软件SPI接口（U8g2底层已替换为裸寄存器SPI3驱动）
 * 
 * Memory LCD特性：
 * - 每个像素是1bit存储单元，刷新时逐行写入
 * - 静态显示无需持续刷新（与TFT不同），功耗极低
 * - 需要周期性VCOM翻转防止屏幕灼伤（burn-in）
 * - 没有专用DC引脚，此处DC复用为DISP（显示使能）
 */
extern U8G2_LS013B7DH03_128X128_F_4W_SW_SPI u8g2;

/*
 * 屏幕帧缓冲区指针
 * 指向U8g2内部的128*128/8=2048字节显存
 * 用于直接操作像素数据实现棋盘格过渡等特殊效果
 * 在fade()函数和某些UI组件中直接修改
 */
extern uint8_t *buf_ptr;

/*
 * 屏幕帧缓冲区长度（字节数）
 * 128x128 / 8 = 2048 bytes
 * 每行16字节，共128行
 */
extern uint16_t buf_len;

/************************************* 显示初始化 *************************************/

/*
 * LCD屏幕初始化
 * - 配置SPI3硬件驱动（裸寄存器操作）
 * - 替换U8g2默认字节回调为自定义硬件SPI回调
 * - 初始化VCOM翻转机制
 * - 设置初始对比度
 */
void lcd_init();

/*
 * 重置VCOM翻转状态
 * 
 * 在屏幕旋转模式改变时调用，确保VCOM计数器重新对齐，
 * 防止因VCOM极性翻转时机偏移导致的边缘白线问题。
 * 同时复位tile_curr_row确保下一次sendBuffer发送全部16行。
 */
void lcd_reset_vcom();

#endif
